"""Build mod/isaac-bot/cards.lua from knowledge/enemy_cards.json (forecast plan step 1, 2026-11-26).

The game's Lua can't read JSON, so the cards' machine parts (move, attacks, body, terrain) are written out as a Lua
table; the human-readable facts stay in the JSON. Cards listed in `same_as` get the same table under their own keys.

  python tools/build_cards.py          write cards.lua
  python tools/build_cards.py --check  exit 1 if cards.lua is out of date (for tests / pre-commit)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "knowledge" / "enemy_cards.json"
OUT = ROOT / "mod" / "isaac-bot" / "cards.lua"
PARTS = ("move", "attacks", "body", "terrain")
# Lua's reserved words can't be bare table keys (a card's "while" field broke the first build)
LUA_WORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in", "local",
             "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"}


def lua(v, ind=""):
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            if x is None:
                continue
            key = k if (k.isidentifier() and k not in LUA_WORDS) else "[" + lua(k) + "]"
            items.append(f"{key} = {lua(x, ind)}")
        return "{ " + ", ".join(items) + " }"
    raise TypeError(type(v))


def build():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    cards = data.get("cards", {})
    rows = []
    for key in sorted(cards):
        c = cards[key]
        part = {k: c[k] for k in PARTS if k in c}
        part["name"] = c.get("name", key)
        for k in [key] + list(c.get("same_as") or []):
            rows.append(f"  [{lua(k)}] = {lua(part)},")
    head = ("-- GENERATED by tools/build_cards.py from knowledge/enemy_cards.json: do not edit by hand.\n"
            "-- Game facts as numbers (read from the game's code, checked against recordings); docs/CARDS.md.\n")
    return head + "return {\n" + "\n".join(rows) + "\n}\n"


def main():
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("cards.lua up to date" if ok else "cards.lua is OUT OF DATE: run python tools/build_cards.py")
        sys.exit(0 if ok else 1)
    OUT.write_bytes(text.encode("utf-8"))  # no byte-order mark (the game's Lua can't read one)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
